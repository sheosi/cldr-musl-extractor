use std::path::Path;

use askama::Template;

/// Represents the data for the locale, every field defaults to the en-US locale. Note: the documentation of the fields is copied from https://pubs.opengroup.org/onlinepubs/9799919799/basedefs/V1_chap07.html#tag_07_03_03
#[derive(Default, Template)]
#[template(path = "musl-locale.txt")]
pub struct Model {
    pub time: ModelTime,
    pub numeric: ModelNumeric,
    pub monetary: ModelMonetary,
    pub messages: ModelMessages,
}

impl Model {
    pub fn to_file(&self, path: &Path) -> anyhow::Result<()> {
        // This can't fail, really
        let render = self.render().expect("");
        std::fs::write(path, render)?;

        Ok(())
    }
}

